-- Salah — published reference-price read contract.
--
-- The *third* published slot, and the only one whose read surface did not exist in this repository.
-- The Android client has always queried `public.metal_prices` — see
-- `app/src/main/java/io/github/towkirahmedrony/salah/data/metalprice/SupabaseRemoteMetalPriceSource.kt`
-- and the column contract in `core/domain/metalprice/MetalPriceParser.kt` — but nothing in this repository
-- defined the object it reads, so the contract existed only as Kotlin constants and prose. This migration
-- pins it in SQL, exactly as `20260515000000_dataset_publications.sql` and
-- `20260601000000_prayer_config_publications.sql` pin theirs.
--
-- NOT APPLIED. This file is reviewed and version-controlled; no migration was run from here. The live
-- Salah project was *read* with the publishable key on 2026-10-18 and already answers the client's exact
-- column list, but with column-level grants rather than the table-level grant below (`select=*` is refused).
-- Applying this file to that project would therefore widen `anon` to every column of an existing table, so
-- it is a definition for a fresh deployment, not a corrective step for the live one. See
-- `docs/SUPABASE_CONTRACT_MATRIX.md` §2.3 and §5, and `docs/SUPABASE_SETUP.md` for how to apply a migration.
--
-- Why a table and not a view
-- --------------------------
-- The two earlier slots read a *view* because this repository also owns the tables behind them. Here the
-- client reads `metal_prices` directly, and **no** table or view with that name exists anywhere in this
-- repository, so there is nothing to build a view over: a view would have to select columns of an object
-- whose name and shape are unknown here, which cannot be written safely and would be inventing schema.
-- A table with the client's own column names is the smallest artifact that makes the read contract
-- checkable. If the deployment already stores these prices in an administrator-owned table under another
-- name, the correct adapter is a read-only view that projects that table onto the columns below — and it
-- belongs in the migration that owns that table, not in a second copy of the data here.
--
-- Additive and re-runnable
-- ------------------------
-- `create table if not exists` means applying this to a project that already has a `metal_prices` table
-- changes nothing — it will not alter, drop or rename a column, and it will not touch a single row. Review
-- before applying: if the existing table has a different shape, this migration is a no-op and the mismatch
-- must be closed by the object's owner. The one statement that can fail on an existing table is the partial
-- unique index below, which fails if the table already holds two active verified rows for the same metal,
-- purity and currency. That is deliberate: the Android client reports such a pair as a conflict and uses
-- neither, so the state should not exist, and a refusal to create the index is the honest report of it.
--
-- Where the prices come from
-- --------------------------
-- The rows are fetched from the upstream market-price provider, validated, reviewed and published by an
-- **administrator workflow that is outside this repository and outside the app**. Salah never contacts that
-- provider and never writes a price: it performs one read-only query against this table with the publishable
-- (anon) key. Inserting, updating and deleting rows is therefore not granted to any client role here.
--
-- The three rules the client relies on, and how each is enforced:
--
--   1. Only an *active, verified* row may be used as an automatic reference rate.
--        - `is_active` and `verification_status` are `not null`, and the client re-checks both rather than
--          trusting that a row which exists has been reviewed. The view-less read means both ends enforce it.
--   2. At most one usable rate per metal, purity and currency.
--        - The partial unique index below makes the ambiguous state unrepresentable, while leaving any
--          number of inactive historical rows possible. The client's own conflict detection stays, because a
--          client must be safe against a database whose constraints are looser than this file.
--   3. A reference rate is an exact decimal in BDT per gram, and is never inferred from a timestamp.
--        - `price_per_gram` is `numeric`, never floating point: the app reads the digits the service sent
--          into a `BigDecimal`. The check constraint refuses a non-positive price outright.

create table if not exists public.metal_prices (
    -- Surrogate key. The publishing workflow owns the values; the app never reads this column.
    id bigint generated by default as identity primary key,

    -- 'GOLD' | 'SILVER'. The app knows no other metal and reports an unknown one rather than mapping it.
    metal_type text not null,

    -- 'K22' | 'K21' | 'K18' | 'TRADITIONAL'. K22 is the app's default selection, a choice made in
    -- `ReferencePricePolicy`, not a claim about any particular item a user owns.
    purity text not null,

    -- BDT per gram, exact. The app refuses a missing, zero, negative or over-precise value rather than
    -- turning it into zero, and there is no hardcoded fallback rate anywhere in the feature.
    price_per_gram numeric not null,

    -- ISO-4217 code. Only 'BDT' is used for the automatic default; the app tolerates and reports others
    -- rather than storing a rate in a currency it did not agree to, so the column is not narrowed to BDT.
    currency text not null default 'BDT',

    -- The organisation the price came from, and a link to it. Descriptive only; the app never follows it.
    source text,
    source_url text,

    -- True when an administrator explicitly activated a manual override for this record.
    override_active boolean not null default false,

    -- Publication status. A row is served to the app only when this is true *and* the status is VERIFIED.
    is_active boolean not null default false,
    verification_status text not null default 'PENDING',

    -- The time the price was verified as effective. This is the only timestamp that may be presented as an
    -- effective or reviewed date: the other three are statements about the plumbing, and the app labels them
    -- as such. Every one of them is nullable, because a publisher that did not record one has said nothing —
    -- and the app must not invent a date to fill the gap.
    effective_at timestamptz,

    -- The time the upstream provider said it last changed the price. Not evidence of when a market price was
    -- actually reached, and never presented as such.
    provider_last_update timestamptz,

    -- The time the provider's response was fetched, and the time this row last changed.
    fetched_at timestamptz,
    updated_at timestamptz not null default now(),

    created_at timestamptz not null default now(),

    constraint metal_prices_metal_type_check check (metal_type in ('GOLD', 'SILVER')),
    constraint metal_prices_purity_check check (purity in ('K22', 'K21', 'K18', 'TRADITIONAL')),
    constraint metal_prices_currency_check check (btrim(currency) <> ''),
    constraint metal_prices_price_check check (price_per_gram > 0),
    constraint metal_prices_verification_check check (verification_status in ('VERIFIED', 'PENDING', 'REJECTED'))
);

comment on table public.metal_prices is
    'Published gold and silver reference rates, BDT per gram. Written by the administrator workflow outside '
    'the app; read-only for app clients through the select policy below.';

comment on column public.metal_prices.price_per_gram is
    'Exact BDT per gram. Read by the app as a BigDecimal; the app accepts at most six decimal places.';

-- At most one active, verified rate per metal, purity and currency: the state the app needs exactly one of.
-- Inactive rows are unconstrained, so a publisher can keep history without ever making the app's choice
-- ambiguous. Fails on a table that already holds a duplicate — which is the report a duplicate deserves.
create unique index if not exists metal_prices_active_basis_key
    on public.metal_prices (metal_type, purity, currency)
    where is_active and verification_status = 'VERIFIED';

-- Access control -------------------------------------------------------------
-- Read-only for app clients, and only for reading. The prices are published market data rather than
-- personal or administrative data, so a row-level filter would add nothing: the policy below grants SELECT
-- and nothing else, and no write privilege is granted to any client role at all.
alter table public.metal_prices enable row level security;

revoke all on public.metal_prices from anon, authenticated;

drop policy if exists metal_prices_public_read on public.metal_prices;
create policy metal_prices_public_read
    on public.metal_prices
    for select
    to anon, authenticated
    using (true);

grant select on public.metal_prices to anon, authenticated;

-- Publishing (insert/update/delete) is a service-role or migration operation and is deliberately not granted
-- to anon or authenticated: with row-level security enabled and no policy for those commands, such a write is
-- denied even if the privilege were later granted by mistake. A service-role key must never be shipped in the
-- Android client; see docs/SUPABASE_SETUP.md.
