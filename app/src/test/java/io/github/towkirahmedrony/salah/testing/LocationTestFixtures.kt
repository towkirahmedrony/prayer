/**
 * Fixtures for the location system.
 *
 * Two kinds of dataset are available and the distinction is deliberate:
 *
 *  - [syntheticDataset] is a handful of hand-written areas with round coordinates and an obvious square
 *    boundary. It makes a failing assertion readable ("Kushtia is not in Khulna") and lets the failure
 *    paths be exercised — an area with no Bangla name, a dataset with no boundary at all — that the
 *    real file does not contain.
 *  - [bundledDataset] reads the **real** files from `app/src/main/assets/location`, so the shipped
 *    dataset is what the tests check: every division present, every district parented correctly, every
 *    coordinate inside the country, and the parser run over the actual bytes rather than over a
 *    convenient miniature.
 *
 * Neither is generated by the code under test: the synthetic one is written by hand, and the real one
 * comes from the files the app ships.
 */

/** A catalog that serves whatever dataset it was given, including `null` to model an unreadable file. */
class FakeBangladeshAreaCatalog(
    var dataset: BangladeshLocationDataset? = null,
) : BangladeshAreaCatalog {
    var loads: Int = 0
        private set

    override suspend fun dataset(): BangladeshLocationDataset? {
        loads++
        return dataset
    }
}

/** A location provider a test drives: one scripted result per request. */
class FakeLocationProvider(
    var servicesEnabled: Boolean = true,
    var result: LocationAcquisitionResult = LocationAcquisitionResult.TimedOut,
) : LocationProvider {

    var calls: Int = 0
        private set
    var lastTimeout: Duration? = null
        private set

    override fun servicesEnabled(): Boolean = servicesEnabled

    override suspend fun currentLocation(timeout: Duration): LocationAcquisitionResult {
        calls++
        lastTimeout = timeout
        return result
    }

    /** A successful fix at [point], with the given accuracy and acquisition time. */
    fun fixAt(
        point: GeoPoint,
        accuracyMetres: Double? = 12.0,
        acquiredAtEpochMillis: Long = FIX_TIMESTAMP,
    ) {
        result = LocationAcquisitionResult.Acquired(
            latitude = point.latitude,
            longitude = point.longitude,
            accuracyMetres = accuracyMetres,
            acquiredAtEpochMillis = acquiredAtEpochMillis,
        )
    }

    companion object {
        /** A fixed instant so a test can assert on acquisition metadata without a moving clock. */
        const val FIX_TIMESTAMP: Long = 1_700_000_000_000L
    }
}

/** A permission state a test sets directly. */
class FakeLocationPermissionSource(
    var state: LocationPermissionState = LocationPermissionState.DENIED,
) : LocationPermissionChecker {
    override fun state(): LocationPermissionState = state
}

/**
 * The dataset the app actually ships, parsed from `app/src/main/assets/location`.
 *
 * Found by walking up from the working directory, because Android unit tests run with the module
 * directory as their working directory while the same tests are also run from the repository root.
 * A missing directory fails loudly with the paths that were tried, rather than silently building an
 * empty dataset that would make every assertion about coverage vacuous.
 */
object BundledDataset {

    private val RELATIVE_CANDIDATES = listOf(
        "app/src/main/assets/location",
        "src/main/assets/location",
        "assets/location",
    )

    /** The directory holding the generated files, or `null` when it cannot be found. */
    fun directory(): File? {
        var base: File? = File(".").absoluteFile
        repeat(SEARCH_DEPTH) {
            val current = base ?: return null
            RELATIVE_CANDIDATES
                .map { relative -> File(current, relative) }
                .firstOrNull { candidate -> File(candidate, AREAS_FILE).isFile }
                ?.let { return it }
            base = current.parentFile
        }
        return null
    }

    /** The real dataset, or a failure naming the paths that were searched. */
    fun load(version: String = "test-bundled"): BangladeshLocationDataset {
        val directory = directory()
            ?: error(
                "The bundled location dataset was not found. Searched upwards from " +
                    "${File(".").absolutePath} for ${RELATIVE_CANDIDATES.joinToString()}.",
            )
        return BangladeshLocationDataset.parse(
            version = version,
            areasText = File(directory, AREAS_FILE).readText(),
            boundaryText = File(directory, BOUNDARY_FILE).readText(),
        )
    }

    const val AREAS_FILE: String = "bd_areas.tsv"
    const val BOUNDARY_FILE: String = "bd_boundary.tsv"

    private const val SEARCH_DEPTH = 5
}

/**
 * A small, hand-written dataset: two divisions, three districts and five upazilas.
 *
 * The square boundary spans the coordinates of every area, so a point inside it is "in Bangladesh"
 * and a point a degree away is not. One upazila deliberately has **no** Bangla name, so the
 * "unmatched name keeps the English one" path is covered by the miniature as well as by the real data.
 */
fun syntheticDataset(version: String = "test-v1"): BangladeshLocationDataset {
    val areas = """
        DIVISION	BD10	BD	Khulna	খুলনা	22.80	89.30
        DIVISION	BD20	BD	Rajshahi	রাজশাহী	24.37	88.60
        DISTRICT	BD1001	BD10	Kushtia	কুষ্টিয়া	23.90	89.12
        DISTRICT	BD1002	BD10	Jashore	যশোর	23.17	89.20
        DISTRICT	BD2001	BD20	Bogura	বগুড়া	24.85	89.37
        UPAZILA	BD1001001	BD1001	Kumarkhali	কুমারখালী	23.86	89.24
        UPAZILA	BD1001002	BD1001	Bheramara		23.99	88.97
        UPAZILA	BD1002001	BD1002	Keshabpur	কেশবপুর	23.05	89.30
        UPAZILA	BD2001001	BD2001	Sherpur	শেরপুর	24.62	89.42
        UPAZILA	BD2001002	BD2001	Shibganj	শিবগঞ্জ	25.02	89.32
    """.trimIndent()

    // A square covering 22.0..25.5 N and 88.5..90.0 E, closed, which contains every area above.
    val boundary = buildString {
        appendLine("0\t22.0\t88.5")
        appendLine("0\t22.0\t90.0")
        appendLine("0\t25.5\t90.0")
        appendLine("0\t25.5\t88.5")
    }

    return BangladeshLocationDataset.parse(
        version = version,
        areasText = areas,
        boundaryText = boundary,
    )
}
