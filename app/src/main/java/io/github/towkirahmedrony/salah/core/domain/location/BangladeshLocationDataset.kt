package io.github.towkirahmedrony.salah.core.domain.location

import io.github.towkirahmedrony.salah.core.model.BangladeshArea
import io.github.towkirahmedrony.salah.core.model.BangladeshAreaLevel
import io.github.towkirahmedrony.salah.core.model.BangladeshAreaRef
import io.github.towkirahmedrony.salah.core.model.BangladeshLocality
import io.github.towkirahmedrony.salah.core.model.BangladeshLocalityKind

/**
 * Salah's bundled Bangladesh geography: every division, district and upazila/thana, with the
 * representative coordinate published for each one, plus the simplified national boundary.
 *
 * **Where the data comes from.** `app/src/main/assets/location/` holds two text files generated by
 * `tools/generate_bd_location_dataset.py` from the OCHA/HDX Bangladesh Common Operational Dataset
 * (`cod-ab-bgd`, CC BY 3.0 IGO) and, for Bangla names only, `nuhil/bangladesh-geocode` (MIT). The
 * script is committed so the derivation is auditable and repeatable; `docs/LOCATION_SYSTEM.md`
 * documents the licences, the join, and what was verified.
 *
 * **Why a text format and a hand-written parser.** The alternative was to depend on a JSON library or
 * ship a generated Kotlin source file. Two tab-separated files of about 83 KB parse in a few
 * milliseconds with no dependency, no code generation step, and no chance of a generated file
 * silently disagreeing with the source. A malformed line is recorded in [rejectedLines] and skipped
 * rather than crashing a first launch or, worse, contributing a half-read area.
 *
 * **Nothing here is inferred.** An area's coordinate is the published centre, the hierarchy is the
 * dataset's p-codes, and a unit whose Bangla name could not be joined keeps `null` instead of a
 * transliteration Salah made up. When the dataset cannot be read at all the app says so; it never
 * falls back to a hand-written list of "popular" places.
 *
 * **The locality layer is a second source, held here on purpose.** `bd_localities.tsv` is derived from
 * OpenStreetMap (ODbL) rather than from COD-AB, and it is a different kind of fact — a named place, not
 * an administrative unit. It lives in this class because the two are read, cached and consumed together:
 * [LocalityResolver] can only accept a locality whose verified district matches the district the
 * administrative layer resolved for the same position, so splitting them would mean two reads of one
 * geography and a rule that needs both in hand anyway. It is optional: a dataset without localities is
 * still usable ([BangladeshLocality] is never required to choose or to describe a location), and a
 * missing or malformed locality layer degrades to the administrative names rather than failing.
 */
class BangladeshLocationDataset private constructor(
    /** The datum these areas came from, e.g. `COD-AB BGD v03 (2023-05-21)`. Shown in the UI. */
    val version: String,
    private val areasById: Map<String, BangladeshArea>,
    private val childrenByParentId: Map<String, List<BangladeshArea>>,
    /** The national boundary, as one or more closed rings. Empty when it could not be read. */
    val boundaryRings: List<List<GeoPoint>>,
    /** Every named locality, ordered by district and then by name. */
    val localities: List<BangladeshLocality>,
    /** Lines the parser refused, kept so the failure is visible in tests and diagnostics. */
    val rejectedLines: List<String>,
) {

    private val localitiesByDistrictId: Map<String, List<BangladeshLocality>> =
        localities.groupBy { it.districtId }

    /** Every area, ordered by level and then by name. */
    val areas: List<BangladeshArea> = areasById.values.sortedWith(
        compareBy({ it.level.ordinal }, { it.name }),
    )

    val divisions: List<BangladeshArea> = areas.filter { it.level == BangladeshAreaLevel.DIVISION }
    val districts: List<BangladeshArea> = areas.filter { it.level == BangladeshAreaLevel.DISTRICT }
    val upazilas: List<BangladeshArea> = areas.filter { it.level == BangladeshAreaLevel.UPAZILA }

    /**
     * True when the dataset can be used to choose a location.
     *
     * Requires the three levels to be present *and* a boundary to check coordinates against: a
     * dataset missing its boundary could not enforce the Bangladesh-only policy, so it is reported as
     * unusable rather than silently accepting any coordinate.
     */
    val isUsable: Boolean
        get() = divisions.isNotEmpty() && districts.isNotEmpty() && upazilas.isNotEmpty() &&
            boundaryRings.isNotEmpty()

    /** The area with [id], or `null` when the dataset does not contain it. */
    fun area(id: String?): BangladeshArea? = id?.let { areasById[it] }

    /**
     * The localities verified as belonging to [districtId], or none when the layer has no entry for it.
     *
     * Keyed by the verified district rather than searched by distance: a locality in another district
     * is not a candidate at all, however close it is, which is what stops a fix on one side of a
     * district border being named after a place on the other side.
     */
    fun localitiesOf(districtId: String?): List<BangladeshLocality> =
        districtId?.let { localitiesByDistrictId[it] }.orEmpty()

    /** True when the locality layer carries at least one entry. */
    val hasLocalities: Boolean get() = localities.isNotEmpty()

    fun districtsOf(divisionId: String): List<BangladeshArea> = childrenOf(divisionId)
        .filter { it.level == BangladeshAreaLevel.DISTRICT }

    fun upazilasOf(districtId: String): List<BangladeshArea> = childrenOf(districtId)
        .filter { it.level == BangladeshAreaLevel.UPAZILA }

    fun childrenOf(parentId: String): List<BangladeshArea> =
        childrenByParentId[parentId].orEmpty().sortedBy { it.name }

    /**
     * The full division → district → upazila chain for [areaId], or `null` when [areaId] is unknown or
     * its parents are missing.
     *
     * Built by walking up the p-code hierarchy rather than by string prefixes, so a change to the
     * numbering scheme in a later dataset cannot silently produce the wrong district.
     */
    fun referenceOf(areaId: String?): BangladeshAreaRef? {
        val starting = area(areaId) ?: return null
        val chain = mutableListOf<BangladeshArea>()
        var current: BangladeshArea? = starting
        while (current != null && chain.size <= LEVEL_COUNT) {
            chain += current
            current = area(current.parentId)
        }

        val division = chain.firstOrNull { it.level == BangladeshAreaLevel.DIVISION } ?: return null
        val district = chain.firstOrNull { it.level == BangladeshAreaLevel.DISTRICT } ?: return null
        val upazila = chain.firstOrNull { it.level == BangladeshAreaLevel.UPAZILA }
        return BangladeshAreaRef.of(division = division, district = district, upazila = upazila)
    }

    /**
     * True when [reference]'s ids all still exist in this dataset, so a stored location can be
     * revalidated after the bundled data is replaced. A reference whose area is gone is reported as
     * such rather than being silently displayed as if it were still valid.
     */
    fun recognises(reference: BangladeshAreaRef): Boolean =
        area(reference.divisionId)?.level == BangladeshAreaLevel.DIVISION &&
            area(reference.districtId)?.level == BangladeshAreaLevel.DISTRICT &&
            (reference.upazilaId == null || area(reference.upazilaId)?.level == BangladeshAreaLevel.UPAZILA)

    override fun toString(): String =
        "BangladeshLocationDataset(version=$version, areas=${areasById.size}, " +
            "localities=${localities.size}, rings=${boundaryRings.size}, rejected=${rejectedLines.size})"

    companion object {
        private const val LEVEL_COUNT = 3

        /** How many refused lines are retained: enough to diagnose, bounded so it cannot grow. */
        private const val MAX_RETAINED_REJECTIONS = 50

        /** The header of the generated areas file, used to recognise a file that is not ours. */
        const val AREA_COLUMNS = 7

        /** The header of the generated boundary file. */
        const val BOUNDARY_COLUMNS = 3

        /** The header of the generated locality file. */
        const val LOCALITY_COLUMNS = 5

        /**
         * Parses the bundled files.
         *
         * Lines starting with `#` and blank lines are comments; everything else must have exactly the
         * documented number of tab-separated fields with usable values, or it is rejected and recorded.
         * An unreadable area file yields a dataset with no areas and therefore
         * `isUsable == false`, which the UI reports as "the location dataset could not be read" rather
         * than as an empty list of divisions.
         */
        fun parse(
            version: String,
            areasText: String,
            boundaryText: String,
            localitiesText: String = "",
        ): BangladeshLocationDataset {
            val rejected = mutableListOf<String>()
            val areas = mutableListOf<BangladeshArea>()

            for (rawLine in areasText.lineSequence()) {
                val line = rawLine.trim()
                if (line.isEmpty() || line.startsWith("#")) continue
                val parsed = parseArea(line)
                if (parsed == null) {
                    if (rejected.size < MAX_RETAINED_REJECTIONS) rejected += line
                } else {
                    areas += parsed
                }
            }

            val distinct = areas.distinctBy { it.id }
            val knownDistrictIds = distinct
                .filter { it.level == BangladeshAreaLevel.DISTRICT }
                .map { it.id }
                .toSet()
            val localities = parseLocalities(localitiesText, knownDistrictIds, rejected)
            val rings = parseBoundary(boundaryText, rejected)

            return BangladeshLocationDataset(
                version = version,
                areasById = distinct.associateBy { it.id },
                childrenByParentId = distinct.groupBy { it.parentId },
                boundaryRings = rings,
                localities = localities,
                rejectedLines = rejected,
            )
        }

        /**
         * Parses the locality file.
         *
         * A locality is only accepted when the district it claims to be in is one this dataset
         * actually defines: a row naming a district the administrative layer does not contain could
         * never be verified against a resolved position, so it is refused and recorded rather than kept
         * as an unusable entry. Points are rejected for the same reasons areas are — an unknown kind, a
         * blank name, a non-numeric or out-of-range coordinate — so a corrupt line cannot contribute a
         * locality with no name or a coordinate in the wrong hemisphere.
         */
        private fun parseLocalities(
            text: String,
            knownDistrictIds: Set<String>,
            rejected: MutableList<String>,
        ): List<BangladeshLocality> {
            val parsed = mutableListOf<BangladeshLocality>()
            for (rawLine in text.lineSequence()) {
                val line = rawLine.trim()
                if (line.isEmpty() || line.startsWith("#")) continue
                val locality = parseLocality(line, knownDistrictIds)
                if (locality == null) {
                    if (rejected.size < MAX_RETAINED_REJECTIONS) rejected += line
                } else {
                    parsed += locality
                }
            }
            return parsed
                .distinctBy { Triple(it.districtId, it.kind, it.name) }
                .sortedWith(compareBy({ it.districtId }, { it.name }))
        }

        private fun parseLocality(
            line: String,
            knownDistrictIds: Set<String>,
        ): BangladeshLocality? {
            val fields = line.split('\t')
            if (fields.size != LOCALITY_COLUMNS) return null

            val kind = BangladeshLocalityKind.ofDatasetValue(fields[0]) ?: return null
            val districtId = fields[1].trim().takeIf { it.isNotEmpty() } ?: return null
            if (districtId !in knownDistrictIds) return null
            val name = fields[2].trim().takeIf { it.isNotEmpty() } ?: return null
            val latitude = fields[3].trim().toDoubleOrNull() ?: return null
            val longitude = fields[4].trim().toDoubleOrNull() ?: return null
            if (!GeoPoint(latitude, longitude).isFinite) return null

            return BangladeshLocality(
                districtId = districtId,
                kind = kind,
                name = name,
                latitude = latitude,
                longitude = longitude,
            )
        }

        private fun parseArea(line: String): BangladeshArea? {
            val fields = line.split('\t')
            if (fields.size != AREA_COLUMNS) return null

            val level = when (fields[0].trim().uppercase()) {
                "DIVISION" -> BangladeshAreaLevel.DIVISION
                "DISTRICT" -> BangladeshAreaLevel.DISTRICT
                "UPAZILA" -> BangladeshAreaLevel.UPAZILA
                else -> return null
            }
            val id = fields[1].trim().takeIf { it.isNotEmpty() } ?: return null
            val parentId = fields[2].trim().takeIf { it.isNotEmpty() } ?: return null
            val name = fields[3].trim().takeIf { it.isNotEmpty() } ?: return null
            val banglaName = fields[4].trim().takeIf { it.isNotEmpty() }
            val latitude = fields[5].trim().toDoubleOrNull() ?: return null
            val longitude = fields[6].trim().toDoubleOrNull() ?: return null
            if (!GeoPoint(latitude, longitude).isFinite) return null

            return BangladeshArea(
                id = id,
                parentId = parentId,
                level = level,
                name = name,
                banglaName = banglaName,
                latitude = latitude,
                longitude = longitude,
            )
        }

        private fun parseBoundary(
            boundaryText: String,
            rejected: MutableList<String>,
        ): List<List<GeoPoint>> {
            val byRing = linkedMapOf<Int, MutableList<GeoPoint>>()
            for (rawLine in boundaryText.lineSequence()) {
                val line = rawLine.trim()
                if (line.isEmpty() || line.startsWith("#")) continue
                val fields = line.split('\t')
                val ringIndex = if (fields.size == BOUNDARY_COLUMNS) fields[0].trim().toIntOrNull() else null
                val latitude = if (fields.size == BOUNDARY_COLUMNS) fields[1].trim().toDoubleOrNull() else null
                val longitude = if (fields.size == BOUNDARY_COLUMNS) fields[2].trim().toDoubleOrNull() else null
                val point = if (latitude != null && longitude != null) GeoPoint(latitude, longitude) else null
                if (ringIndex == null || point == null || !point.isFinite) {
                    if (rejected.size < MAX_RETAINED_REJECTIONS) rejected += line
                    continue
                }
                byRing.getOrPut(ringIndex) { mutableListOf() } += point
            }
            // A ring with fewer than three points cannot enclose anything; keeping it would make
            // `isInside` answer "false" for a place that may well be inside the country.
            return byRing.values.filter { it.size >= 3 }.map { it.toList() }
        }
    }
}
